# schmale Zeichen: Breite in Spalten (Rest wird links ausgerichtet abgeschnitten)
NARROW = {':':(2,1), '.':(1,2), ',':(1,2), '!':(2,1), "'":(2,1), ' ':(0,3), ';':(1,2)}
def cols(ch):
    rows=G[ch]
    first,width=NARROW.get(ch,(0,5))
    out=[]
    for c in range(first,first+width):
        v=0
        for r in range(7):
            if rows[r][c]=='#': v|=1<<r
        out.append(v)
    return out
lines=["#pragma once","#include <Arduino.h>","// 5x7-Pixelschrift fuer FLYGLINJE (eigene Zeichnung). Je Spalte ein Byte, Bit 0 = oberste Zeile.","namespace Font {","struct Glyph { char ch; uint8_t width; uint8_t cols[5]; };","const Glyph GLYPHS[] = {"]
for ch in G:
    c=cols(ch); c5=c+[0]*(5-len(c))
    lit = "'\\\\'" if ch=='\\' else ("'\\''" if ch=="'" else ("'\\x%02x'"%ord(ch) if ord(ch)<32 else "'%s'"%ch))
    lines.append("  {%s, %d, {%s}},"%(lit,len(c),",".join("0x%02X"%v for v in c5)))
lines+=["};","const size_t COUNT = sizeof(GLYPHS) / sizeof(GLYPHS[0]);",
"inline const Glyph *find(char c) {",
"  if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';",
"  for (size_t i = 0; i < COUNT; i++) if (GLYPHS[i].ch == c) return &GLYPHS[i];",
"  return find('?');",
"}",
"}  // namespace Font",""]
